// Параметр fields у list-инструментов: какие поля объекта вернуть.
//
// Зачем он вообще нужен. FieldNames в v5 обязателен, «отдай всё» метода нет, и для
// инструментов, возвращающих сотни объектов, набор приходится держать узким: каждое
// лишнее поле умножается на число объектов и раздувает ответ в контексте модели.
// Но узкий набор — это чужое решение за вызывающего: именно так 12.09.2026 ставка
// ставилась без данных аукциона, а тип объявления определялся без Type/Subtype.
// Поэтому набор по умолчанию остаётся узким, а расширить его может тот, кто спрашивает.
//
// Литерал, а не z.string(): перечисление закрыто снимком WSDL, и имя не из него Директ
// отбивает ошибкой 8000 уже на боевом вызове. Схема — единственная документация, которую
// видит модель, поэтому допустимые значения обязаны быть типом, а не прозой в описании.
import { z } from "zod"

export function fieldsField(values: readonly [string, ...string[]], defaults: readonly string[]) {
  return z
    .array(z.literal(values))
    .check(z.minLength(1, { error: "Список полей пуст" }))
    .optional()
    .meta({ description: `Какие поля вернуть; по умолчанию ${defaults.join(", ")}` })
}
